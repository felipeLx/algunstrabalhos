SELECT * FROM (
    SELECT 
        CAST(COD_DOCUMENTO AS DECIMAL(30,0))                 	AS COD_DOCUMENTO,
        DTH_AUTUACAO,
        COD_CNJ,
        COD_CNJ_SIGILO,
        ID_SIGILO,
        CAST(COD_TIPO_PROCESSO AS INT)                          AS COD_CLASSE_SISTEMA,
        CAST(COD_CLASSE_EXTERNA AS VARCHAR(255))                AS COD_CLASSE_EXIBICAO,
        CAST(NM_CLASSE AS VARCHAR(255))                         AS NM_CLASSE,
        CAST(COD_COMPETENCIA AS INT)                            AS COD_COMPETENCIA,
        CAST(NM_COMPETENCIA AS VARCHAR(255))                    AS NM_COMPETENCIA,
        CAST(IND_CRIMINAL AS VARCHAR(255))                      AS IND_CRIMINAL,
        CAST(IND_CIVEL AS VARCHAR(255))                         AS IND_CIVEL,
        CAST(COD_ASSUNTO AS INT)                                AS COD_ASSUNTO_PRINCIPAL,
        CAST(NM_ASSUNTO_PRINCIPAL AS VARCHAR(255))              AS NM_ASSUNTO_PRINCIPAL,
        CAST(IND_ORIGINARIO AS VARCHAR(255))                    AS IND_ORIGINARIO,
        CAST(IND_AUTOASSOCIADO_ORIGEM AS VARCHAR(255))          AS IND_AUTOASSOCIADO_ORIGEM,
        CAST(ID_PROCESSO_RELACIONADO AS DECIMAL(30,0))          AS ID_PROCESSO_RELACIONADO,
        CAST(NUM_PROCESSO_ORIGEM AS VARCHAR(255))               AS NUM_PROCESSO_ORIGEM,
        CAST(COD_CLASSE_ORIGEM AS VARCHAR(255))                 AS COD_CLASSE_ORIGEM,
        CAST(CLASSE_ORIGEM AS VARCHAR(255))                     AS CLASSE_ORIGEM, 
        CAST(IND_SISTEMA_ORIGEM AS VARCHAR(255))                AS IND_SISTEMA_ORIGEM,
        CAST(COD_VARA_ORIGEM AS VARCHAR(255))                   AS COD_VARA_ORIGEM,
        CAST(VARA_ORIGEM AS VARCHAR(255))                       AS VARA_ORIGEM,
        CAST(IND_PRIORIDADE_IDOSO AS VARCHAR(255))				AS IND_PRIORIDADE_IDOSO,
        CAST(IND_PRIORIDADE_IDOSO_80 AS VARCHAR(255))           AS IND_PRIORIDADE_IDOSO_80,
	    CAST(IND_DOENCA_GRAVE AS VARCHAR(255))                  AS IND_DOENCA_GRAVE,
	    CAST(IND_PRIORIDADE_DEFICIENTE AS VARCHAR(255))         AS IND_PRIORIDADE_DEFICIENTE,
	    CAST(IND_MENOR AS VARCHAR(255))                         AS IND_MENOR,  
        CAST(IND_DESTITUICAO_PODER_FAMILIAR AS VARCHAR(255))    AS IND_PODER_FAMILIAR,
        cast(IND_CRIME_ADM_PUBLICO as varchar(255))				as IND_CRIME_ADM_PUBLICO,
        CAST(IND_SISTEMA AS VARCHAR(255))                       AS IND_SISTEMA
    FROM dim_2inst_ouro.tb_dim_processo_ejud
    UNION ALL 
    SELECT
        -- IDENTIFICADORES DO PROCESSO
        CAST(ID_PROCESSO AS DECIMAL(30,0))                   AS COD_DOCUMENTO,
        DTH_AUTUACAO,
        COD_CNJ,
        COD_CNJ_SIGILO,
        ID_SIGILO,
        -- INDICADORES DE CLASSE DO PROCESSO
        CAST(ID_CLASSE_JUDICIAL AS INT)                      AS COD_CLASSE_SISTEMA,
        CAST(COD_CLASSE AS VARCHAR(255))                     AS COD_CLASSE_EXIBICAO,
        CAST(DES_CLASSE AS VARCHAR(255))                     AS NM_CLASSE,
        -- INDICADORES DE COMPETENCIA
        CAST(COD_COMPETENCIA AS INT)                         AS COD_COMPETENCIA,
        CAST(DES_COMPETENCIA AS VARCHAR(255))                AS NM_COMPETENCIA,
        CAST(SIN_CRIMINAL AS VARCHAR(255))                   AS IND_CRIMINAL,
        CAST(SIN_CIVEL AS VARCHAR(255))                      AS IND_CIVEL,
        -- INDICADORES DE ASSUNTO
        CAST(COD_MNI_ASSUNTO_JUDICIAL AS INT)                AS COD_ASSUNTO_PRINCIPAL,
        CAST(DES_ASSUNTO AS VARCHAR(255))                    AS NM_ASSUNTO_PRINCIPAL,
        -- INDICADORES DO PROCESSO NA ORIGEM
        CAST(IND_ORIGINARIO AS VARCHAR(255))                 AS IND_ORIGINARIO,
        CAST(IND_AUTOASSOCIADO_ORIGEM AS VARCHAR(255))       AS IND_AUTOASSOCIADO_ORIGEM,
        CAST(ID_PROCESSO_RELACIONADO AS DECIMAL(30,0))       AS ID_PROCESSO_RELACIONADO,
        CAST(NUM_PROCESSO_ORIGEM AS VARCHAR(255))            AS NUM_PROCESSO_ORIGEM,
        CAST(COD_CLASSE_ORIGEM AS VARCHAR(255))              AS COD_CLASSE_ORIGEM,
        CAST(CLASSE_ORIGEM AS VARCHAR(255))                  AS CLASSE_ORIGEM, 
        CAST(IND_SISTEMA_ORIGEM AS VARCHAR(255))             AS IND_SISTEMA_ORIGEM,
        CAST(COD_ORGAO_ORIGEM AS VARCHAR(255))               AS COD_VARA_ORIGEM,
        CAST(ORGAO_ORIGEM AS VARCHAR(255))                   AS VARA_ORIGEM,
        --INDICADORES DE PROCESSO
        CAST(IDOSOS AS VARCHAR(255))						 AS IND_PRIORIDADE_IDOSO,
        CAST(IDOSOS_80_MAIS AS VARCHAR(255))				 AS IND_PRIORIDADE_IDOSO_80,
        CAST(DOENCA_GRAVE AS VARCHAR(255))				 	 AS IND_DOENCA_GRAVE,
        CAST(PRIORIDADE_DEFICIENTE AS VARCHAR(255))			 AS IND_PRIORIDADE_DEFICIENTE,
        CAST(CRIANCA_ADOLESCENTE AS VARCHAR(255))			 AS IND_MENOR,       
        CAST(IND_PODER_FAMILIAR AS varchar(255))			 AS IND_PODER_FAMILIAR,
        cast(IND_CRIME_ADM_PUBLICO as varchar(255))			 as IND_CRIME_ADM_PUBLICO,
        CAST(IND_SISTEMA AS VARCHAR(255))                    AS IND_SISTEMA
    FROM dim_2inst_ouro.tb_dim_processo_eproc2g
) ;